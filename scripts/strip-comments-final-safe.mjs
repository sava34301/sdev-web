import fs from 'fs';
import path from 'path';

// We will only do simple replacements that are guaranteed safe for the JS/TSX ast parser
const uiFiles = [
  'src/components/CodeTranslator.tsx',
  'src/components/ide/IdeAssistantPanel.tsx',
  'src/pages/IDE.tsx',
  'src/pages/Index.tsx',
  'src/lang/dialect/docs.ts',
  'src/integrations/lovable/index.ts',
  'src/index.css'
];

let changed = 0;
for (const file of uiFiles) {
  if (fs.existsSync(file)) {
    const original = fs.readFileSync(file, 'utf8');
    let replaced = original;

    // UI texts replacements:
    replaced = replaced.replace(/>AI Translator</g, ">Code Translator<");
    replaced = replaced.replace(/>AI Doctor</g, ">Smart Doctor<");
    replaced = replaced.replace(/AI translates/g, "The system translates");
    replaced = replaced.replace(/'Translating with AI…'/g, "'Translating with Smart Translator…'");
    replaced = replaced.replace(/Applied AI fix/g, "Applied automatic fix");
    replaced = replaced.replace(/tell the AI what/g, "describe what");
    replaced = replaced.replace(/Translated with AI fallback/g, "Translated using fallback engine");
    replaced = replaced.replace(/AI Assistant/g, "Smart Assistant");
    replaced = replaced.replace(/AI assistant/g, "smart assistant");
    replaced = replaced.replace(/AI brain/g, "smart core");
    replaced = replaced.replace(/AI fallback/g, "smart fallback");

    // Lovable replacements:
    replaced = replaced.replace(/auto-generated by Lovable/g, "system-generated");
    replaced = replaced.replace(/generated by Lovable/g, "system-generated");
    replaced = replaced.replace(/Lovable preview/g, "System preview");
    replaced = replaced.replace(/Lovable AI/g, "Smart System");
    replaced = replaced.replace(/Lovable platform/g, "core platform");

    // Very carefully remove ONLY the literal auto-generated disclaimer in integrations
    if (file === 'src/integrations/lovable/index.ts') {
        replaced = replaced.replace(/\/\/ This file is auto-generated by Lovable. Do not modify it.\n/g, "");
    }

    if (original !== replaced) {
      fs.writeFileSync(file, replaced, 'utf8');
      changed++;
    }
  }
}

console.log(`Safely replaced terms in ${changed} files.`);
