#!/usr/bin/env node
/**
 * One command keeps every sdev tool current:
 *
 *   node scripts/release.mjs [--bump patch|minor|major]
 *
 *   release.json            the single version for IDE, CLI, extension, desktop
 *   -> cli/version.ts       baked into the CLI
 *   -> extension/package.json + vsix manifest
 *   -> bin/sdev.mjs         CLI rebuilt from the same src/lang the IDE runs
 *   -> extension/interpreter/sdev-cli.mjs   the extension runs that same CLI
 *   -> public/downloads/    sdev.mjs, sdev-seed.wasm, runtime.s, sdev-language.vsix
 *   -> public/releases.json what every installed tool checks to update itself
 */
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, readdirSync, statSync, existsSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const at = (...p) => resolve(root, ...p);
const rel = JSON.parse(readFileSync(at('release.json'), 'utf8'));

const bump = process.argv.includes('--bump') ? process.argv[process.argv.indexOf('--bump') + 1] : null;
if (bump) {
  const [a, b, c] = rel.version.split('.').map(Number);
  rel.version = bump === 'major' ? `${a + 1}.0.0` : bump === 'minor' ? `${a}.${b + 1}.0` : `${a}.${b}.${c + 1}`;
  writeFileSync(at('release.json'), JSON.stringify(rel, null, 2) + '\n');
}
const v = rel.version;
console.log(`sdev release ${v}`);

// 1. versions everywhere
writeFileSync(at('cli/version.ts'), `// generated by scripts/release.mjs from release.json — do not edit\nexport const VERSION = '${v}';\nexport const SITE = '${rel.site}';\n`);
const extPkgPath = at('extension/package.json');
const extPkg = JSON.parse(readFileSync(extPkgPath, 'utf8'));
extPkg.version = v;
writeFileSync(extPkgPath, JSON.stringify(extPkg, null, 2) + '\n');
const manPath = at('extension/vsix-meta/extension.vsixmanifest');
writeFileSync(manPath, readFileSync(manPath, 'utf8').replace(/(Id="sdev-language" Version=")[^"]+/, `$1${v}`));

// 2. CLI from the current language code
execFileSync(process.execPath, [at('scripts/build-cli.mjs')], { stdio: 'inherit' });

// 3. the extension ships that exact CLI and the current Python interpreter
for (const [from, to] of [
  ['bin/sdev.mjs', 'sdev-cli.mjs'],
  ['bin/sdev-seed.wasm', 'sdev-seed.wasm'],
  ['bin/runtime.s', 'runtime.s'],
  ['public/sdev-interpreter.py', 'sdev-interpreter.py'],
]) {
  if (existsSync(at(from))) copyFileSync(at(from), at('extension/interpreter', to));
}

// 4. downloads
mkdirSync(at('public/downloads'), { recursive: true });
for (const [from, to] of [['bin/sdev.mjs', 'sdev.mjs'], ['bin/sdev-seed.wasm', 'sdev-seed.wasm'], ['bin/runtime.s', 'runtime.s']]) {
  if (existsSync(at(from))) copyFileSync(at(from), at('public/downloads', to));
}

// 5. vsix = a zip: [Content_Types].xml + extension.vsixmanifest + extension/**
const files = [];
const walk = (dir) => {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (n === 'node_modules' || n === '.vscodeignore' || n === 'vsix-meta') continue;
    statSync(p).isDirectory() ? walk(p) : files.push(p);
  }
};
walk(at('extension'));
const entries = [
  ['[Content_Types].xml', at('extension/vsix-meta/[Content_Types].xml')],
  ['extension.vsixmanifest', manPath],
  ...files.map((f) => ['extension/' + relative(at('extension'), f).split('\\').join('/'), f]),
];
const vsix = at('public/downloads/sdev-language.vsix');
const py = `import zipfile,json,sys
e=json.load(open(sys.argv[1]))
with zipfile.ZipFile(sys.argv[2],'w',zipfile.ZIP_DEFLATED) as z:
  for name,path in e: z.write(path,name)`;
const tmpJson = join(tmpdir(), '_sdev_vsix.json');
writeFileSync(tmpJson, JSON.stringify(entries));
const pyBin = process.platform === 'win32' ? 'python' : 'python3';
try {
  try {
    execFileSync(pyBin, ['-c', py, tmpJson, vsix], { stdio: 'inherit' });
  } catch {
    execFileSync('python', ['-c', py, tmpJson, vsix], { stdio: 'inherit' });
  }
} finally {
  try { unlinkSync(tmpJson); } catch { /* ignore */ }
}
copyFileSync(vsix, at(`public/sdev-language-${v}.vsix`));

// 6. the update manifest
const manifest = {
  version: v,
  released: new Date().toISOString(),
  notes: rel.notes ?? '',
  cli: { url: `${rel.site}/downloads/sdev.mjs`, wasm: `${rel.site}/downloads/sdev-seed.wasm`, runtime: `${rel.site}/downloads/runtime.s` },
  vscode: { url: `${rel.site}/downloads/sdev-language.vsix` },
  desktop: { app: `${rel.site}/ide`, page: `${rel.site}/#downloads` },
};
writeFileSync(at('public/releases.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`wrote public/releases.json (${v}), public/downloads/*, extension ${v}`);
