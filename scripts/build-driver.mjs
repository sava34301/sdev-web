// Bake the self-hosted driver bytecode.
//
// The driver program (lang/compiler/driver.sdev) is source-independent, so it
// only has to be compiled once. This script uses the reference oracle as a
// build-time tool and writes the result to `src/lang-bridge/driver-artifact.mjs`.
//
//   node scripts/build-driver.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { compile as oracleCompile } from '../src/lang-bridge/oracle/compile.mjs';

export async function buildDriver() {
  const driverSrc = await readFile(new URL('../lang/compiler/driver.sdev', import.meta.url), 'utf8');
  const { bytecode, stringPool } = oracleCompile(driverSrc);
  return { bytecode, stringPool };
}

const hex = (u8) => Buffer.from(u8).toString('hex');

function formatCArray(name, bytes) {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push('  ' + Array.from(bytes.subarray(i, i + 16), (b) => `0x${b.toString(16).padStart(2, '0')}`).join(', '));
  }
  return `static const uint32_t ${name}_LEN = ${bytes.length};\nstatic const uint8_t ${name}[] = {\n${lines.join(',\n')}\n};`;
}

if (process.argv[1] && resolve(fileURLToPath(import.meta.url)) === resolve(process.argv[1])) {
  const { bytecode, stringPool } = await buildDriver();
  const out = `// GENERATED by scripts/build-driver.mjs — do not edit by hand.
// Bytecode for the self-hosted SDEV driver (lang/compiler/driver.sdev).
// bytecode: ${bytecode.length} bytes, string pool: ${stringPool.length} bytes.

export const DRIVER_BYTECODE_HEX = '${hex(bytecode)}';
export const DRIVER_POOL_HEX = '${hex(stringPool)}';
`;
  await writeFile(new URL('../src/lang-bridge/driver-artifact.mjs', import.meta.url), out);

  const header = `// Auto-generated from driver-artifact.mjs
#pragma once
#include <stdint.h>
${formatCArray('BAKED_DRIVER_BC', bytecode)}
${formatCArray('BAKED_DRIVER_POOL', stringPool)}
`;
  await writeFile(new URL('../src/lang-bridge/native/driver-embedded.h', import.meta.url), header);
  console.log(`driver-artifact.mjs + driver-embedded.h written — bc=${bytecode.length}, pool=${stringPool.length}`);
}
